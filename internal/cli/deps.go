package cli

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"github.com/dmc5179/olm-catalog-reconstruct/internal/deps"
	"github.com/dmc5179/olm-catalog-reconstruct/internal/isc"
)

// ExitError carries a specific process exit code.
type ExitError struct {
	Code int
	Msg  string
}

func (e *ExitError) Error() string { return e.Msg }

func newDepsCommand(g *globalOpts) *cobra.Command {
	var (
		knownFiles  []string
		noKnown     bool
		additionsTo string
		jsonTo      string
		strict      bool
	)
	cmd := &cobra.Command{
		Use:   "deps ISC.yaml [ISC.yaml...]",
		Short: "Check that every operator an ImageSetConfiguration mirrors has its dependencies mirrored too",
		Long: `deps works out exactly which bundles oc-mirror v2 would mirror for the given
ImageSetConfigurations (same filter as 'replay'), then checks every selected bundle's
dependencies:

  olm.package.required   another package within a version range
  olm.gvk.required       an API that some other package must provide
  olm.constraint         all/any/not combinations of the above (CEL is flagged for review)
  known (undeclared)     dependencies an operator installs at runtime without declaring
                         them (built-in list, extend with --known-deps)

Missing dependencies are resolved from the loaded catalogs, and the fixes are checked
recursively. The fixes are written as a supplementary ImageSetConfiguration; pass it
to 'replay' or 'deps' alongside the original to confirm, or merge it into your config.

oc-mirror v2 itself never adds dependencies (by design), so anything reported here
would be missing from the mirror.`,
		Args: cobra.MinimumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			loader, err := g.loader()
			if err != nil {
				return err
			}
			var known []deps.KnownDep
			if !noKnown {
				if known, err = deps.DefaultKnownDeps(); err != nil {
					return err
				}
			}
			for _, f := range knownFiles {
				k, err := deps.LoadKnownDeps(f)
				if err != nil {
					return err
				}
				known = append(known, k...)
			}
			configs := make([]*isc.ImageSetConfiguration, 0, len(args))
			for _, p := range args {
				c, err := isc.Load(p)
				if err != nil {
					return err
				}
				configs = append(configs, c)
			}
			res, err := deps.Check(cmd.Context(), loader, configs, deps.Options{Known: known})
			if err != nil {
				return err
			}
			var additionsYAML []byte
			if res.Additions != nil {
				if additionsYAML, err = res.Additions.Marshal(); err != nil {
					return err
				}
				additionsYAML = append([]byte("# Generated by olm-reconstruct deps: operator dependencies missing from\n# "+strings.Join(args, ", ")+"\n"), additionsYAML...)
				if additionsTo != "" {
					if err := os.WriteFile(additionsTo, additionsYAML, 0o644); err != nil {
						return err
					}
				}
			}
			if jsonTo != "" {
				data, err := json.MarshalIndent(res, "", "  ")
				if err != nil {
					return err
				}
				if err := os.WriteFile(jsonTo, append(data, '\n'), 0o644); err != nil {
					return err
				}
			}
			printDeps(cmd.OutOrStdout(), res, additionsYAML, additionsTo)
			if strict && res.HasProblems() {
				return &ExitError{Code: 3, Msg: "missing operator dependencies found"}
			}
			return nil
		},
	}
	f := cmd.Flags()
	f.StringArrayVar(&knownFiles, "known-deps", nil, "additional YAML file of undeclared dependencies (same format as the built-in list)")
	f.BoolVar(&noKnown, "no-known-deps", false, "do not use the built-in list of undeclared dependencies")
	f.StringVarP(&additionsTo, "output", "o", "", "write suggested ImageSetConfiguration additions to this file (default: print them)")
	f.StringVar(&jsonTo, "json", "", "write the full result as JSON to this file")
	f.BoolVar(&strict, "strict", false, "exit with code 3 when dependencies are missing, unresolved or conflicting")
	return cmd
}

func printDeps(w io.Writer, res *deps.Result, additionsYAML []byte, additionsTo string) {
	byStatus := map[string][]deps.Finding{}
	for _, f := range res.Findings {
		byStatus[f.Status] = append(byStatus[f.Status], f)
	}
	fmt.Fprintf(w, "Checked %d bundles; %d requirements already satisfied by the configuration.\n\n", res.Checked, res.Satisfied)

	section := func(status, title string) {
		fs := byStatus[status]
		if len(fs) == 0 {
			return
		}
		sort.SliceStable(fs, func(i, j int) bool {
			if (fs[i].Via == "") != (fs[j].Via == "") {
				return fs[i].Via == ""
			}
			return fs[i].Package < fs[j].Package
		})
		fmt.Fprintf(w, "%s (%d)\n", title, len(fs))
		for _, f := range fs {
			fmt.Fprintf(w, "  %s requires %s  [%s]\n", f.Bundle, f.Requirement, f.Kind)
			if f.Via != "" {
				fmt.Fprintf(w, "      pulled in by: %s\n", f.Via)
			}
			if len(f.Have) > 0 {
				fmt.Fprintf(w, "      configured versions: %s\n", strings.Join(f.Have, ", "))
			}
			if f.Source != "" {
				fmt.Fprintf(w, "      note: %s\n", f.Source)
			}
			if f.Resolution != "" {
				fmt.Fprintf(w, "      -> %s\n", f.Resolution)
			}
		}
		fmt.Fprintln(w)
	}
	section(deps.StatusAdded, "MISSING - fix added to suggested additions")
	section(deps.StatusUnresolved, "MISSING - no fix found in the loaded catalogs")
	section(deps.StatusConflict, "CONFLICT")
	section(deps.StatusManual, "MANUAL REVIEW")
	section(deps.StatusPlatform, "PLATFORM APIs (informational)")
	section(deps.StatusSkipped, "SKIPPED BUNDLES (informational) - a newer mirrored bundle in the same channel skips these, so they are upgrade sources, not install targets")

	if len(res.Findings) == 0 {
		fmt.Fprintln(w, "All declared and known dependencies are satisfied.")
		return
	}
	if additionsYAML != nil {
		if additionsTo != "" {
			fmt.Fprintf(w, "Suggested additions written to %s\n", additionsTo)
		} else {
			fmt.Fprintf(w, "Suggested ImageSetConfiguration additions:\n---\n%s", additionsYAML)
		}
	}
}
